def match_filters(record, from_date, to_date, level, source):
    # Функция проверяет, подходит ли запись (record) под заданные пользователем фильтры.
    # Возвращает True (подходит) или False (не подходит).

    # Распаковываем кортеж, нам нужны только время (ts), уровень (lvl) и источник (src).
    # Остальные поля (код события и сообщение) мы игнорируем (обозначаем _).
    ts, lvl, src, _, _ = record

    # Фильтр по времени "С" (начало включительно).
    # Если фильтр задан и время записи МЕНЬШЕ времени начала — отбрасываем.
    if from_date and ts.replace(tzinfo=None) < from_date:
        return False

    # Фильтр по времени "По" (конец исключительно).
    # Если фильтр задан и время записи БОЛЬШЕ ИЛИ РАВНО времени конца — отбрасываем.
    if to_date and ts.replace(tzinfo=None) >= to_date:
        return False

    # Фильтр по уровню логирования. Если задан и не совпадает — отбрасываем.
    if level and lvl != level:
        return False

    # Фильтр по источнику. Если задан и не совпадает — отбрасываем.
    if source and src != source:
        return False

    # Если запись прошла все проверки (ни один if не сработал), значит она подходит.
    return True